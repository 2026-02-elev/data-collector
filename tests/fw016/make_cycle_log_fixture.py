# Regenerates tests/fixtures/cellguard_cycle_20261025_132800.log (SIMULATED DEVICE, not a bench capture)
# Author: Yongho Ahn <nanhosoft@gmail.com>
"""Runs ``cg-collect cycle`` against sim016 (unmodified 0.1.6 firmware + plant model) with the
on-load tap inversion of the 2026-10-25 bench run injected during the discharge, then writes
the raw UART log in cellguard_cycle.py's trace format (local time Asia/Seoul, starting
2026-10-25 13:28:00.000). Two lines are damaged on purpose (CRC, truncated) and one non-trace
line is added, so the importer's checks are exercised.

    python3 tests/fw016/make_cycle_log_fixture.py tests/fw016/build/sim016
"""
import datetime as dt
import json
import sys
import tempfile
from pathlib import Path
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from cg_collector import cli  # noqa: E402
from cg_collector.transport import SimTransport  # noqa: E402

OUT = ROOT / "tests" / "fixtures" / "cellguard_cycle_20261025_132800.log"
START = dt.datetime(2026, 10, 25, 13, 28, 0, tzinfo=ZoneInfo("Asia/Seoul"))


def main(sim: str) -> None:
    def make(_a):
        t = SimTransport(sim)
        t.control("INJECT LOADED_INVERSION 1")
        return t

    cli._transport = make
    with tempfile.TemporaryDirectory() as d:
        cli.main(["--sim", sim, "--data-dir", d, "--boot-check", "off", "cycle", "--charge-to", "200",
                  "--discharge-to", "120", "--i-am-supervising"])
        raw = [json.loads(l) for f in sorted(Path(d, "outbox").glob("raw-*.jsonl")) for l in open(f)]
    raw = [r for r in raw if r["dir"] != "RUN"]
    t0 = dt.datetime.fromisoformat((raw[0].get("pi_received_utc") or raw[0]["pi_sent_utc"]).replace("Z", "+00:00"))
    lines = []
    for r in raw:
        utc = dt.datetime.fromisoformat((r.get("pi_received_utc") or r["pi_sent_utc"]).replace("Z", "+00:00"))
        stamp = (START + (utc - t0)).strftime("%Y-%m-%d %H:%M:%S.%f")[:-3]
        lines.append(f"{stamp} {'RX' if r['dir'] == 'N>P' else 'TX'} {r['frame']}")
    cgts = [i for i, l in enumerate(lines) if " RX $CGT," in l]
    i = cgts[3]
    lines[i] = lines[i][:-4] + "0000"              # CRC damaged in transit
    j = cgts[5]
    lines[j] = lines[j][:lines[j].index("*") - 7]  # truncated frame
    lines.insert(0, "# SIMULATED DEVICE: generated by tests/fw016/make_cycle_log_fixture.py (sim016, 0.1.6 firmware)")
    OUT.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"{len(lines)} lines -> {OUT}")


if __name__ == "__main__":
    main(sys.argv[1])
