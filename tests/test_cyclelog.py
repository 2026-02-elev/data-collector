# Importing cellguard_cycle.py serial traces (0.1.6-LOAD-VERIFY) into samples / events / diagnostics
# Author: Yongho Ahn <nanhosoft@gmail.com>
import json
from pathlib import Path

import jsonschema

from cg_collector import cli

ROOT = Path(__file__).resolve().parents[1]
LOG = ROOT / "tests" / "fixtures" / "cellguard_cycle_20261025_132800.log"  # generated by sim016 (see its first line)


def load(out, name):
    return [json.loads(l) for l in (out / f"{name}.jsonl").read_text().splitlines()]


def test_import_cycle_log(tmp_path, capsys, normalized_schema, diagnostic_schema):
    out = tmp_path / "imp"
    assert cli.main(["import-cycle-log", str(LOG), "--out", str(out), "--log-tz", "Asia/Seoul"]) == 0
    summary = json.loads(capsys.readouterr().out)
    lines = LOG.read_text().splitlines()
    rep = json.loads((out / "import_report.json").read_text())
    assert rep["lines"] == len(lines) and rep["rx"] + rep["tx"] == len(lines) - 1
    assert rep["non_trace_lines"][0]["ref"] == f"{LOG.name}:1"           # the comment line is reported, not parsed
    assert rep["crc_or_format_errors"] == 2 and rep["unknown_types"] == 0  # one bad CRC, one truncated frame
    assert rep["firmware_versions"] == ["0.1.6-LOAD-VERIFY"] and rep["frame_types"]["CGY"] == 1
    assert rep["sources"][0]["sha256"] and rep["log_timezone"] == "Asia/Seoul"
    assert summary["records"] == rep["records"]

    raw = load(out, "raw")
    assert raw[0]["dir"] == "RUN" and raw[0]["run_start_utc"] == "2026-10-25T04:28:00.000000Z"  # KST -> UTC
    rows = raw[1:]
    assert len(rows) == len(lines) - 1
    for r in rows:  # original line, direction and local time preserved
        src = lines[r["source_line"] - 1]
        assert src.startswith(r["log_local_time"]) and src.endswith(r["frame"])
        assert (" RX " in src) == (r["dir"] == "N>P")
    bad = [r for r in rows if r["error"]]
    assert len(bad) == 2 and any("CRC" in r["error"] for r in bad)

    samples = load(out, "samples")
    assert samples
    for s in samples:
        jsonschema.validate(s, normalized_schema)
        assert s["pack_current_a"] is None and s["current_quality"] == "INA219_UNAVAILABLE"  # no INA219 in the trace
        assert s["firmware_version"] == "0.1.6-LOAD-VERIFY"
        assert s["source"] == "synthetic"   # the fixture's CGV carries HOST_SIM_BUILD; a rig trace is measured
    oks = [s for s in samples if s["record_status"] == "OK"]
    for s in oks:  # every record points at the CGT line it was built from, and copies its voltages exactly
        name, n = s["raw_log_ref"].rsplit(":", 1)
        line = lines[int(n) - 1]
        assert name == LOG.name and " RX $CGT," in line
        cells = [int(x) for x in line.split("$")[1].split(",")[3:7]]
        assert s["cell_voltage_v"] == [c / 1000 for c in cells]
    # the damaged CGT is not invented: its slot is missing, and the CRC error is counted
    assert any(s["record_status"] == "MISSING_TELEMETRY" for s in samples)
    assert sum(s["transport"]["crc_errors_since_last"] + s["transport"]["format_errors_since_last"]
               for s in samples) == 2

    diags = load(out, "diagnostics")
    for d in diags:
        jsonschema.validate(d, diagnostic_schema)
    kinds = [d["kind"] for d in diags]
    assert "LOAD_TAP_SUSPECT_SNAPSHOT" in kinds and "REST_VERIFY" in kinds
    cgy = diags[kinds.index("LOAD_TAP_SUSPECT_SNAPSHOT")]
    assert cgy["detail"]["rested_cell_voltage"] is False and cgy["raw_log_ref"].startswith(LOG.name + ":")
    assert lines[int(cgy["raw_log_ref"].rsplit(":", 1)[1]) - 1].endswith(cgy["frame"])
    stop = [d["detail"] for d in diags if d["kind"] == "STAGE_STOP"]
    assert [(s["stage"], s["stop_class"]) for s in stop] == [("RAMP", "TARGET_REACHED"), ("DRAIN", "ABORTED")]
    events = load(out, "events")
    req = [(e["evidence"]["command"], e["requested_value"]) for e in events if e["event_type"] == "REQUESTED"]
    assert ("RAMP", 200) in req and ("DRAIN", 120) in req and ("OFF", "OFF") in req
    drain_stop = [e for e in events if e["evidence"].get("cge", {}).get("cge_code") == "DRAIN_STOP"][0]
    assert drain_stop["evidence"]["stage_stop"]["abort_reason"] == "LOAD_TAP_UNSTABLE"


def test_import_rejects_files_without_trace_lines(tmp_path, capsys):
    f = tmp_path / "x.log"
    f.write_text("hello\n")
    assert cli.main(["import-cycle-log", str(f), "--out", str(tmp_path / "o")]) == 2


def test_clock_step_backwards_is_reported_not_reordered(tmp_path):
    lines = LOG.read_text().splitlines()[1:40]
    # the Pi clock steps back 2 s in the middle (NTP correction): keep the file order, report it
    k = 20
    stamp = lines[k][:23]
    import datetime as dt
    back = (dt.datetime.strptime(stamp, "%Y-%m-%d %H:%M:%S.%f") - dt.timedelta(seconds=2))
    lines[k] = back.strftime("%Y-%m-%d %H:%M:%S.%f")[:-3] + lines[k][23:]
    f = tmp_path / "cellguard_cycle_x.log"
    f.write_text("\n".join(lines) + "\n")
    out = tmp_path / "o"
    assert cli.main(["import-cycle-log", str(f), "--out", str(out), "--log-tz", "UTC"]) == 0
    rep = json.loads((out / "import_report.json").read_text())
    assert rep["time_reversals"][0]["ref"] == f"{f.name}:{k + 1}" and rep["time_reversals"][0]["back_by_s"] >= 1.9
    raw = load(out, "raw")[1:]
    assert [r["source_line"] for r in raw] == sorted(r["source_line"] for r in raw)   # file order kept
    assert raw[k]["log_local_time"] == lines[k][:23]                                   # original stamp kept
